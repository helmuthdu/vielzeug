const NON_COLLAPSIBLE_PACKAGE_PATHS = new Set(['/refine/']);

const isPackageSidebarPath = (path: string): boolean => /^\/[a-z]+\/$/.test(path);

const makePackageSidebarsCollapsible = (sidebar: DefaultTheme.SidebarMulti): DefaultTheme.SidebarMulti => {
  return Object.fromEntries(
    Object.entries(sidebar).map(([path, items]) => {
      if (!isPackageSidebarPath(path) || NON_COLLAPSIBLE_PACKAGE_PATHS.has(path)) {
        return [path, items];
      }

      const normalizedItems = (items as any).map((item: any) => {
        if (!('items' in item)) return item;

        return {
          ...item,
          collapsed: item.collapsed ?? item.text === 'API Reference',
        };
      });

      return [path, normalizedItems];
    }),
  ) as DefaultTheme.SidebarMulti;
};

// ---------------------------------------------------------------------------
// llms.txt + llms-full.txt — copy pre-generated files from codex data/
// ---------------------------------------------------------------------------

function copyLlmsTxt(siteConfig: { outDir: string }): void {
  const codexData = resolve(__dirname, '../../packages/codex/data');

  for (const name of ['llms.txt', 'llms-full.txt'] as const) {
    const src = resolve(codexData, name);

    if (existsSync(src)) {
      copyFileSync(src, resolve(siteConfig.outDir, name));
    }
  }
}

